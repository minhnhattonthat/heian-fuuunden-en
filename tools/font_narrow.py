def main():
    img = Image.new("RGB", (16 * 8, 6 * 8), "white")
    for ch, rows in ART.items():
        assert len(rows) <= 8, ch
        width = max(len(r) for r in rows)
        assert width <= 7, ch
        i = ord(ch) - 0x20
        x0, y0 = (i % 16) * 8, (i // 16) * 8
        for y, r in enumerate(rows):
            for x, p in enumerate(r):
                if p == "#":
                    img.putpixel((x0 + x, y0 + y), (0, 0, 0))
    SHEET.parent.mkdir(exist_ok=True)
    img.save(SHEET)
    print("wrote", SHEET)


if __name__ == "__main__":
    main()
